def ptext(p):
    return "".join(t.text or "" for t in p._p.iter(qn("w:t")))


def all_paras():
    return [Paragraph(el, None) for el in body.iter(qn("w:p"))]


def find(sub, nth=0, start_after=None):
    hits = [p for p in all_paras() if sub in ptext(p)]
    assert len(hits) > nth, f"paragraph not found: {sub[:70]}"
    return hits[nth]


def set_text(p, new):
    runs = [r for r in p._p.findall(qn("w:r")) if r.find(qn("w:t")) is not None]
    assert runs, "no text run"
    for i, r in enumerate(runs):
        t = r.find(qn("w:t"))
        t.text = new if i == 0 else ""
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")


def replace_sub(p, old, new):
    for r in p.runs:
        if old in r.text:
            r.text = r.text.replace(old, new)
            return
    full = ptext(p)
    assert old in full, f"substring not found: {old[:60]}"
    set_text(p, full.replace(old, new))


def edit(find_sub, old, new, nth=0):
    replace_sub(find(find_sub, nth), old, new)
    log.append(f"edited: {old[:60]}")


def insert_after(anchor_el, like_p, text):
    el = copy.deepcopy(like_p._p)
    anchor_el.addnext(el)
    set_text(Paragraph(el, None), text)
    return el


def table_with_header(first_cell_text):
    for t in doc.tables:
        if t.rows[0].cells[0].text.strip() == first_cell_text:
            return t
    raise AssertionError("table not found: " + first_cell_text)


def row_of(table, first_cell_start):
    for r in table.rows:
        if r.cells[0].text.strip().startswith(first_cell_start):
            return r
    raise AssertionError("row not found: " + first_cell_start)


def set_cell(cell, text):
    set_text(cell.paragraphs[0], text)
    for extra in cell.paragraphs[1:]:
        extra._p.getparent().remove(extra._p)


