"""
Measure the context path (spotlighting + scan) on documents from dataset_v2 TEST, which no layer was trained or tuned on.

    python PrepareForBCTĐ2/tools/eval_context_scan.py

Four groups of documents, each sent through FirewallOrchestrator.process_context as ONE untrusted chunk:
  poisoned_plain     document with an attack sentence inserted (attack_insert_*); should be quarantined + taint
  clean_plain        document with a harmless note (benign_insert, clean); should pass untouched
  poisoned_hidden    a clean document plus the SAME attack sentence hidden in an HTML comment; the comment must
                     be removed and flagged
  harmless_hidden    a clean document plus a harmless HTML comment; the comment must be removed, NO taint

Reported: rates with 95% Wilson intervals, and the latency of the scan. Writes results/context_scan_eval.json.
"""
import json
import os
import random
import re
import sys
import time

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "evaluation"))

from eval_layer1 import wilson  # noqa: E402
from firewall.orchestrator import FirewallOrchestrator  # noqa: E402
from firewall.spotlight import datamark  # noqa: E402

N = 200
INNER = r"<untrusted[^>]*>\n(.*?)\n</untrusted>"      # the text between the delimiters of the context block
HARMLESS_COMMENTS = ["Ghi chú nội bộ: cập nhật bảng giá vào cuối tuần, người soạn: bộ phận kinh doanh",
                     "TODO: review the layout of this section before publishing it to the website",
                     "Bản nháp thứ ba, đã chỉnh sửa theo góp ý của phòng pháp chế ngày hôm qua",
                     "generated by the content management system, version 4.2, do not edit by hand"]


def scan(engine, text, sid):
    return engine.process_context([{"id": "d", "text": text, "source": "email"}], session_id=sid)


def rate(hits, n):
    return {"n": n, "hits": hits, "rate": round(hits / n, 4), "ci95": wilson(hits, n)}


def main() -> None:
    rng = random.Random(0)
    data = pd.read_csv(os.path.join(ROOT, "data", "processed", "dataset_v2_test.csv"), keep_default_na=False)
    poisoned = data[(data.label_binary == 1) & data.variant.str.startswith("attack_insert") & (data.insert_text != "")]
    clean = data[(data.label_binary == 0) & data.variant.isin(["benign_insert", "clean"]) & (data.text.str.len() >= 200)]
    poisoned = poisoned.sample(min(N, len(poisoned)), random_state=0)
    clean_a = clean.sample(min(N, len(clean)), random_state=1)
    clean_b = clean.sample(min(N, len(clean)), random_state=2)
    clean_c = clean.sample(min(N, len(clean)), random_state=3)
    attack_sentences = poisoned["insert_text"].tolist()
    rng.shuffle(attack_sentences)

    engine = FirewallOrchestrator()
    scan(engine, "warm up", "warm")
    results, timings = {}, []

    def run(name, texts, check, removed=None, kept_share=None):
        hits, misses, removed_hits, shares = 0, [], 0, []
        for i, text in enumerate(texts):
            t0 = time.perf_counter()
            out = scan(engine, text, f"{name}-{i}")
            timings.append((time.perf_counter() - t0) * 1000)
            args = (out, text) if name.startswith("poisoned_plain") else (out,)
            if removed is not None and removed(*args):
                removed_hits += 1
            if kept_share is not None:
                shares.append(kept_share(*args))
            if check(*args):
                hits += 1
            elif len(misses) < 4:
                misses.append({"text": text[:160], "decision": out["decision"], "tainted": out["tainted"]})
        results[name] = {**rate(hits, len(texts)), "examples_of_failures": misses}
        if removed is not None:      # the instruction left the context even when the session was not tainted
            results[name]["removed_from_context"] = rate(removed_hits, len(texts))
        if shares:                   # how much of the document still reaches the model (1.0 = all of it)
            ordered = sorted(shares)
            results[name]["share_of_document_kept"] = {"median": round(ordered[len(ordered) // 2], 3), "mean": round(float(np.mean(ordered)), 3)}

    inserted = dict(zip(poisoned["text"], poisoned["insert_text"]))

    def attack_gone(o, text):
        """The inserted attack sentence is not in what the model would read."""
        return datamark(inserted[text]) not in o["sanitized_context"]

    # texts are looked up by their content, so run() gets a closure over the current text through the zip below
    docs_poisoned = poisoned["text"].tolist()
    run("poisoned_plain_attack_cut_and_session_tainted", docs_poisoned,
        lambda o, t: o["decision"] == "SANITIZE" and o["tainted"] and attack_gone(o, t),
        removed=lambda o, t: attack_gone(o, t) and o["decision"] == "SANITIZE",
        kept_share=lambda o, t: len(" ".join(re.findall(INNER, o["sanitized_context"], re.S)).replace("ˆ", " ")) / max(len(t), 1))
    run("clean_plain_passed_untouched", clean_a["text"].tolist(),
        lambda o: o["decision"] == "ALLOW" and not o["tainted"])
    run("poisoned_hidden_comment_removed_and_flagged", [t + f"\n<!-- {s} -->" for t, s in zip(clean_b["text"], attack_sentences)],
        lambda o: o["tainted"] and "<!--" not in o["sanitized_context"] and o["decision"] == "SANITIZE",
        removed=lambda o: "<!--" not in o["sanitized_context"] and o["decision"] == "SANITIZE")
    run("harmless_hidden_comment_removed_no_taint", [t + f"\n<!-- {rng.choice(HARMLESS_COMMENTS)} -->" for t in clean_c["text"]],
        lambda o: o["decision"] == "SANITIZE" and not o["tainted"] and "<!--" not in o["sanitized_context"])

    ordered = sorted(timings)
    results["latency_ms_per_document"] = {"n": len(ordered), "p50": round(ordered[len(ordered) // 2], 1),
                                          "p95": round(ordered[int(len(ordered) * 0.95)], 1), "mean": round(float(np.mean(ordered)), 1)}
    out_path = os.path.join(ROOT, "PrepareForBCTĐ2", "results", "context_scan_eval.json")
    with open(out_path, "w", encoding="utf-8") as handle:
        json.dump(results, handle, indent=2, ensure_ascii=False)
    for key, value in results.items():
        if "rate" in value:
            extra = f"  | removed from context {value['removed_from_context']['hits']}" if "removed_from_context" in value else ""
            extra += f"  | document kept: median {value['share_of_document_kept']['median']}" if "share_of_document_kept" in value else ""
            print(f"{key:48s} {value['hits']:>4}/{value['n']:<4} = {value['rate']:.3f}  CI95 {value['ci95']}{extra}")
        else:
            print(key, value)
    print("wrote", out_path)


if __name__ == "__main__":
    main()
